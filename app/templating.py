def navigation(user, modules: dict[str, str]) -> list[dict]:
    if user is None:
        return []
    if user.role == "housekeeping":
        return [{"href": "/housekeeping", "label": "Housekeeping", "icon": "sparkles"}]
    items = [
        {"href": "/", "label": "Tableau de bord", "icon": "home"},
        {"href": "/planning", "label": "Planning", "icon": "calendar"},
        {"href": "/reservations", "label": "Réservations", "icon": "document"},
        {"href": "/guests", "label": "Clients", "icon": "users"},
        {"href": "/housekeeping", "label": "Housekeeping", "icon": "sparkles"},
    ]
    if modules:
        items.append({"href": "/pos", "label": "Points de vente", "icon": "bag"})
    items += [
        {"href": "/night-audit", "label": "Audit de nuit", "icon": "moon"},
        {"href": "/invoices", "label": "Factures", "icon": "cash"},
        {"href": "/reports", "label": "Rapports", "icon": "chart"},
    ]
    if user.role == "admin":
        items.append({"href": "/admin", "label": "Administration", "icon": "cog"})
    return items


def flash(request: Request, message: str, kind: str = "success") -> None:
    # Réaffectation obligatoire : la session Starlette ne détecte pas la mutation d'une liste existante.
    request.session["flashes"] = [*request.session.get("flashes", []), {"kind": kind, "msg": message}]


async def render(request: Request, db: AsyncSession, name: str, status_code: int = 200, **context):
    hs = await load_hotel_settings(db)
    modules = await enabled_modules(db)
    user = getattr(request.state, "user", None)
    context.update(
        hs=hs, modules=modules, user=user, flashes=request.session.pop("flashes", []),
        today=today_of(hs), now=now_of(hs), csrf_token=get_csrf_token(request.session),
        nav=navigation(user, modules), current_path=request.url.path,
    )
    return templates.TemplateResponse(request, name, context, status_code=status_code)


def render_error(request: Request, status_code: int, title: str, message: str):
    return templates.TemplateResponse(
        request, "errors/error.html",
        {"status_code": status_code, "title": title, "message": message,
         "csrf_token": get_csrf_token(request.session) if "session" in request.scope else ""},
        status_code=status_code,
    )
