def icon(name: str, cls: str = "h-5 w-5") -> Markup:
    path = ICONS.get(name, ICONS["document"])
    return Markup(
        f'<svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke-width="1.6" '
        f'stroke="currentColor" class="{cls}" aria-hidden="true"><path stroke-linecap="round" '
        f'stroke-linejoin="round" d="{path}"/></svg>'
    )


@pass_context
def _money(context, value) -> str:
    hs = context.get("hs")
    return format_money(value, hs.currency_symbol if hs else "DA")


def _date(value) -> str:
    if isinstance(value, (date, datetime)):
        return value.strftime("%d/%m/%Y")
    return "—"


def _datetime(value) -> str:
    return value.strftime("%d/%m/%Y %H:%M") if isinstance(value, datetime) else "—"


def _weekday(value: date) -> str:
    return ["Lun", "Mar", "Mer", "Jeu", "Ven", "Sam", "Dim"][value.weekday()]


templates.env.filters.update(money=_money, date=_date, dt=_datetime, weekday=_weekday)
